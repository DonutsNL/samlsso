            if ($index_exists->count() == 0) {
                // Create statement
                $query = "ALTER TABLE `$table` ADD INDEX `sessionId_idx` (`sessionId`)";
                // Perform the query.
                // https://github.com/DonutsNL/samlsso/issues/102
                if ($DB->doQuery($query)) {
