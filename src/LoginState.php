                $where = [
                    LoginState::IDP_ID        => $idpId,
                    LoginState::PHASE         => LoginState::PHASE_GLPI_AUTH,
                    LoginState::LAST_ACTIVITY => ['<', $cutoff]
                ];

                $DB->update(
                    LoginState::getTable(),
                    [
                        LoginState::PHASE => LoginState::PHASE_TIMED_OUT
                    ],
                    $where
                );
            }
        }
    }

