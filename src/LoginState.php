        if (
            $DB->tableExists($table)                    &&   // Table should exist
            $DB->fieldExists($table, 'excludedPath')
        ) {   // If the excluded Path field exists (older versions) drop it. 
            // Drop the field;
            $migration->dropField($table, 'excludedPath');
        }

        if (
