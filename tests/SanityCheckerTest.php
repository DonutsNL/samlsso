    use GlpiPlugin\Samlsso\Config;
    use GlpiPlugin\Samlsso\Config\ConfigEntity;
    use GlpiPlugin\Samlsso\Exclude;
    use GlpiPlugin\Samlsso\LoginState;
    use GlpiPlugin\Samlsso\ClaimMap;
    use GlpiPlugin\Samlsso\ObservedClaim;
    use GlpiPlugin\Samlsso\Utility\SanityChecker;

    /**
     * Mock database specifically validating strict table and column presence and case sensitivity.
     */
    class SanityCheckerMockDB
    {
        /** @var array<string, array<string, bool>> Map of table names to existing columns */
        public array $schema = [];

        /**
         * Initialize mock database with the real table schemas generated by install().
         */
        public function __construct()
        {
            $this->schema = [
                getTableForItemType(Config::class) => [
                    ConfigEntity::ID => true,
                    ConfigEntity::NAME => true,
                    ConfigEntity::INACTIVITY_TIMEOUT => true,
                ],
                getTableForItemType(Exclude::class) => [
                    'id' => true,
                    Exclude::EXCLUDEPATH => true,
                ],
                getTableForItemType(LoginState::class) => [
                    LoginState::STATE_ID => true,
                    LoginState::LAST_ACTIVITY => true,
                    LoginState::PHASE => true,
                ],
                getTableForItemType(ClaimMap::class) => [
                    ClaimMap::ID => true,
                    ClaimMap::CONFIGS_ID => true,
                    ClaimMap::TARGET_TYPE => true,
                ],
                getTableForItemType(ObservedClaim::class) => [
                    ObservedClaim::ID => true,
                    ObservedClaim::CONFIGS_ID => true,
                    ObservedClaim::SAML_CLAIM => true,
                ],
            ];
        }

        /**
         * Check if table exists in mock DB.
         *
         * @param string $table Table name.
         * @return bool True if table exists.
         */
        public function tableExists(string $table): bool
        {
            return isset($this->schema[$table]);
        }

        /**
         * Check if column exists in table (strictly case-sensitive, matching MySQL/PHP array behavior).
         *
         * @param string $table Table name.
         * @param string $field Field name.
         * @param bool $use_cache Cache option.
         * @return bool True if field exists with exact casing.
         */
        public function fieldExists(string $table, string $field, bool $use_cache = true): bool
        {
            if (!isset($this->schema[$table])) {
                return false;
            }
            return isset($this->schema[$table][$field]);
        }
    }

    /**
     * Class SanityCheckerTest
     */
    class SanityCheckerTest
    {
        /**
         * Test that SanityChecker passes against the standard valid installed schema.
         *
         * @throws \Exception if check fails unexpectedly.
         */
        public function testCheckPassesOnValidSchema(): void
        {
            global $DB;
            $mockDb = new SanityCheckerMockDB();
            $DB = $mockDb;

            $result = SanityChecker::check();
            if (!$result['status']) {
                $failedMessages = implode("; ", $result['messages']);
                throw new \Exception("SanityChecker::check() failed on valid schema: $failedMessages");
            }

            echo "✅ SanityChecker: validated passing check on correct schema\n";
        }

        /**
         * Test that SanityChecker detects missing table.
         *
         * @throws \Exception if failure is not detected.
         */
        public function testCheckFailsOnMissingTable(): void
        {
            global $DB;
            $mockDb = new SanityCheckerMockDB();
            $targetTable = getTableForItemType(ObservedClaim::class);
            unset($mockDb->schema[$targetTable]);
            $DB = $mockDb;

            $result = SanityChecker::check();
            if ($result['status']) {
                throw new \Exception("SanityChecker::check() should have failed for missing table $targetTable");
            }

            $foundTableError = false;
            foreach ($result['messages'] as $message) {
                if (str_contains($message, "Database table missing: $targetTable")) {
                    $foundTableError = true;
                    break;
                }
            }

            if (!$foundTableError) {
                throw new \Exception("Expected table missing message for $targetTable was not found");
            }

            echo "✅ SanityChecker: detected missing table correctly\n";
        }

        /**
         * Test that SanityChecker detects missing column with case sensitivity.
         *
         * @throws \Exception if missing column is not detected.
         */
        public function testCheckFailsOnMissingOrMismatchedColumn(): void
        {
            global $DB;
            $mockDb = new SanityCheckerMockDB();
            $targetTable = getTableForItemType(ObservedClaim::class);
            unset($mockDb->schema[$targetTable][ObservedClaim::SAML_CLAIM]);
            $DB = $mockDb;

            $result = SanityChecker::check();
            if ($result['status']) {
                throw new \Exception("SanityChecker::check() should have failed when saml_claim column is missing");
            }

            $foundColumnError = false;
            foreach ($result['messages'] as $message) {
                if (str_contains($message, "Column missing in table $targetTable: saml_claim")) {
                    $foundColumnError = true;
                    break;
                }
            }

            if (!$foundColumnError) {
                throw new \Exception("Expected column missing message for saml_claim was not found");
            }

            echo "✅ SanityChecker: detected missing or mismatched column correctly\n";
        }
    }
}

namespace {
    $test = new GlpiPlugin\Samlsso\Tests\SanityCheckerTest();
    try {
        $test->testCheckPassesOnValidSchema();
        $test->testCheckFailsOnMissingTable();
        $test->testCheckFailsOnMissingOrMismatchedColumn();
        $test = null;
    } catch (\Exception $e) {
        echo "\n❌ Test Failed: " . $e->getMessage() . "\n";
        exit(1);
    }
}
